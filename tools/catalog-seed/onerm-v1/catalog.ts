export type Laterality = 'bilateral' | 'unilateral' | 'alternating';

/** A movement, regardless of the equipment it is done with. */
export interface SourceBase {
  readonly slug: string;
  readonly es: string;
  readonly en: string;
  readonly mechanic: Mechanic;
  readonly targetMuscles: readonly SourceMuscle[];
  readonly secondaryMuscles: readonly SourceMuscle[];
  readonly aliases: readonly string[];
}

/** A base done with one piece of equipment: one exercise of the catalog. */
export interface SourceVariant {
  /** `<equipment>-<base>`, as in v1: the external id of the exercise. */
  readonly slug: string;
  readonly base: SourceBase;
  readonly equipment: SourceEquipment;
  readonly laterality: Laterality;
}

