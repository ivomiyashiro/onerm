const baseBySlug = new Map(
  baseSeeds.map(([slug, es, en, mechanic, targetMuscles, secondaryMuscles, aliases = []]) => [
    slug,
    { slug, es, en, mechanic, targetMuscles, secondaryMuscles, aliases },
  ]),
);

export const ONERM_V1_VARIANTS: readonly SourceVariant[] = variantSeeds.map(
  ([baseSlug, equipment, laterality = 'bilateral']) => {
    const base = baseBySlug.get(baseSlug);
    if (!base) throw new Error(`onerm-v1: variant of an unknown base "${baseSlug}"`);
    return { slug: `${equipment}-${baseSlug}`, base, equipment, laterality };
  },
);
