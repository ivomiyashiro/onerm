type Row = readonly [ExerciseKey, ExerciseRole, number];

/** The exercises of a template day, in order, with their ids (`PLT-FB3-A1`). */
function day(
  templateId: string,
  code: string,
  name: string,
  position: number,
  rows: readonly Row[],
) {
  const id = `${templateId}-${code}`;
  const exercises: TemplateExercise[] = rows.map(([key, role, sets], index) => ({
    id: `${id}${index + 1}`,
    exerciseId: EXERCISE_IDS[key],
    position: index + 1,
    role,
    sets,
  }));
  return { id, name, position, exercises };
}

